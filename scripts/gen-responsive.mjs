import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const outDir = path.resolve("src/assets/optimized/r");
await mkdir(outDir, { recursive: true });

const jobs = [
  { src: "src/assets/devotional/dev1.jpg", key: "dev1" },
  { src: "src/assets/devotional/dev3.jpg", key: "dev3" },
  { src: "src/assets/recepmarriage/bride1.jpg", key: "bride1" },
  { src: "src/assets/recepmarriage/bride7.jpg", key: "bride7" },
  { src: "src/assets/recepmarriage/r1.jpg", key: "r1" },
  { src: "src/assets/recepmarriage/r9.jpg", key: "r9" },
  { src: "src/assets/recepmarriage/r10.jpg", key: "r10" },
  { src: "src/assets/recepmarriage/r12.jpg", key: "r12" },
  { src: "src/assets/anniversory/anni10.jpg", key: "anni10" },
  { src: "src/assets/baby.jpg", key: "baby" },
  { src: "src/assets/birthday/birthday1.png", key: "birthday1" },
  { src: "src/assets/birthday/birthday10.png", key: "birthday10" },
  { src: "src/assets/s10.png", key: "s10" },
  { src: "src/assets/s12.png", key: "s12" },
  { src: "src/assets/s13.png", key: "s13" },
  { src: "src/assets/s14.png", key: "s14" },
  { src: "src/assets/s42.png", key: "s42" },
  { src: "src/assets/f1.png", key: "f1" },
  { src: "src/assets/f2.png", key: "f2" },
  { src: "src/assets/f20.png", key: "f20" },
  { src: "src/assets/f24.png", key: "f24" },
  { src: "src/assets/gift.jpg", key: "gift" },
  { src: "src/assets/flower/ff1.jpg", key: "ff1" },
];

const widths = [240, 480, 960];

// Assets are referenced BY DIRECT named imports in the generated code below so
// the bundler cannot tree-shake the derived WebP/AVIF files away.
const imports = [];
const body = [];
const rel = (p) => path.relative(path.resolve("src/utils"), p).split(path.sep).join("/");

for (const job of jobs) {
  const { src, key } = job;
  const meta = await sharp(src).metadata();
  const origW = meta.width;

  imports.push(`import ${key}_orig from ${JSON.stringify(rel(path.resolve(src)))};`);
  for (const w of widths) {
    const wpath = path.resolve(outDir, `${key}-${w}.webp`);
    imports.push(`import ${key}_${w}w from ${JSON.stringify(rel(wpath))};`);
    const apath = path.resolve(outDir, `${key}-${w}.avif`);
    imports.push(`import ${key}_${w}w_avif from ${JSON.stringify(rel(apath))};`);
  }
  const fbPath = path.resolve(outDir, `${key}-960.webp`);
  imports.push(`import ${key}_fb from ${JSON.stringify(rel(fbPath))};`);

  await sharp(src)
    .rotate()
    .resize({ width: Math.min(960, origW), withoutEnlargement: true, fit: "inside" })
    .webp({ quality: 74, effort: 4 })
    .toFile(fbPath);
  for (const w of widths) {
    const tw = Math.min(w, origW);
    if (tw <= 0) continue;
    await sharp(src)
      .rotate()
      .resize({ width: tw, withoutEnlargement: true, fit: "inside" })
      .webp({ quality: 72, effort: 4 })
      .toFile(path.resolve(outDir, `${key}-${w}.webp`));
    await sharp(src)
      .rotate()
      .resize({ width: tw, withoutEnlargement: true, fit: "inside" })
      .avif({ quality: 58, effort: 4 })
      .toFile(path.resolve(outDir, `${key}-${w}.avif`));
  }

  const avifSrcSet = widths
    .map((w) => "${" + key + "_" + w + "w_avif} " + w + "w")
    .join(", ");
  const webpSrcSet = widths
    .map((w) => "${" + key + "_" + w + "w} " + w + "w")
    .join(", ");
  body.push(
    "  RESP_BY_ORIGINAL[" + key + "_orig] = {\n" +
      "    avif: `" + avifSrcSet + "`,\n" +
      "    webp: `" + webpSrcSet + "`,\n" +
      "    fallback: " + key + "_fb,\n" +
      "    original: " + key + "_orig,\n" +
      "    w: " + origW + ",\n" +
      "  };"
  );
  console.log(`${src} (${origW}px) -> 3 widths (webp+avif) + 960 fallback`);
}

const file =
  "// AUTO-GENERATED by scripts/gen-responsive.mjs - do not edit by hand.\n" +
  imports.join("\n") +
  "\n\n" +
  "// Maps an original asset's module URL to a responsive set of pre-built srcset\n" +
  "// strings. All derived assets are referenced by direct named imports so they\n" +
  "// are never tree-shaken from the production bundle.\n" +
  "export const RESP_BY_ORIGINAL = {};\n" +
  body.join("\n") +
  "\n";

await writeFile(path.resolve("src/utils/generatedImages.js"), file, "utf8");
console.log(`Wrote src/utils/generatedImages.js with ${jobs.length} entries`);
